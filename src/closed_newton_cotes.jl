        return [[1.0, 0.0] [0.8, 0.2] [0.6, 0.4] [0.4, 0.6] [0.2, 0.8] [0.0, 1.0]], [0.06597222222222222, 0.2604166666666667, 0.1736111111111111, 0.1736111111111111, 0.2604166666666667, 0.06597222222222222]
