        return [[1.0, 0.0] [0.75, 0.25] [0.5, 0.5] [0.25, 0.75] [0.0, 1.0]], [0.07777777777777778, 0.35555555555555557, 0.13333333333333333, 0.35555555555555557, 0.07777777777777778]
    end
